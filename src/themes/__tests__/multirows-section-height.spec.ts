/**
 * «Высота» секции «Мультиряды» правит высотой рядов, а стыки рядов не рвутся
 * скруглениями.
 *
 * Откуда задача. Владелец, 19.09 (bloom, живой конструктор): «высота настройка
 * вообще не работает» и «если отступов нет — бордер-радиусы не нужны, нужно
 * убрать эти прогалы».
 *
 * Причина первой части. У КАЖДОГО ряда в сиде лежит свой `size` (дефолт
 * панели), а порты тем читали его как приоритетный: `r.size ? r.size : p.size`.
 * Значит секционная «Высота» не меняла НИЧЕГО ни на одной из пяти тем — замер
 * через `POST /preview/block` на живом сайте владельца: секция `large` + ряды
 * `small` отдавали `aspect-[16/9]`, то есть ответ ряда.
 *
 * ПОПРАВКА 20.09 — ТРЕБОВАНИЕ СМЕНИЛОСЬ, А НЕ РЕГРЕССИЯ. Чинили это эвристикой
 * `perRowSizesDiffer` («одинаковые размеры у всех рядов ≡ мерчант их не
 * трогал»), и она вылечила одну сторону монеты, сломав другую: владелец 20.09
 * «при размерах в рядах большой/средний они становятся маленькими». Мерчант
 * доводит выбор до последнего ряда, размеры совпадают — и весь выбор
 * отменяется; у секции с одним рядом per-row размер не работал никогда.
 * Эвристика снята: рендер снова читает `r.size ?? p.size`, а секционная
 * «Высота» при изменении прописывается конструктором во ВСЕ ряды
 * (`CustomFieldsPanel.updateProp`) — так живы обе настройки без угадывания.
 * Поведение сторожит РЕНДЕРОМ `multirows-row-size.spec.ts`; здесь остаётся
 * то, что рендером не проверить.
 *
 * Что сторожим:
 *  1. эвристика не вернулась ни в один порт — она уже приходила дважды;
 *  2. секция остаётся фолбэком для ряда без своего размера;
 *  3. у bloom на ≥lg (там же, где `lg:gap-0` ставит ряды вплотную) скруглений
 *     нет — иначе между рядами снова появятся просветы подложки. Мобильные
 *     скругления при этом целы: там ряды идут с зазором.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(__dirname, '../../..');
const read = (rel: string) => readFileSync(resolve(ROOT, rel), 'utf8');
const THEMES = ['rose', 'bloom', 'satin', 'flux', 'vanilla'] as const;
const portOf = (theme: string) => `themes/${theme}/src/components/sections/MultiRows.astro`;

describe('«Мультиряды»: высота секции и стыки рядов', () => {
  it.each(THEMES)('%s: эвристика «одинаковые размеры ≡ не выбирал» не вернулась', (theme) => {
    // Комментарии срезаем: в шапке порта имя эвристики упомянуто НАМЕРЕННО —
    // там объяснено, почему её убрали. Запрет — на живой код.
    const src = read(portOf(theme)).replace(/\/\/.*$/gm, '');

    // Она приходила дважды и оба раза выглядела правдоподобно, поэтому имя
    // держим под запретом целиком, а не только в тернарнике аспекта.
    expect(src).not.toMatch(/perRowSizesDiffer/);
    expect(src).not.toMatch(/rowSizes\.some/);
    // САБОТАЖ-ОПОРА: срезали комментарии, а не файл целиком.
    expect(src).toMatch(/aspectFor\(/);
  });

  it.each(THEMES)('%s: секция остаётся фолбэком для ряда без своего размера', (theme) => {
    const src = read(portOf(theme));

    // Ряд главнее, секция — запасное значение. Пустая «Высота» ≡ дефолт
    // панели ('medium' у satin со своим puckConfig, 'small' у остальных):
    // расхождение этих двух ловит panel-default-is-noop.
    expect(src).toMatch(/r\.size && r\.size !== "inherit" \? r\.size : \(p\.size \?\? "(?:small|medium)"\)/);
  });

  it.each([
    ['rose', 'lg'],
    ['bloom', 'lg'],
    ['flux', 'lg'],
    ['vanilla', 'lg'],
    // satin переходит на две колонки раньше остальных.
    ['satin', 'md'],
  ])('%s: текст в паре имеет внутренний отступ с той ширины, где ряд двухколоночный', (theme, bp) => {
    const src = read(portOf(theme));

    // Владелец, 19.09 (Высота=Средняя / Ширина=Большая / Позиция=Слева):
    // «отступы при таком конфиге ломаются». Замер живого рендера показывал
    // заголовок ровно от кромки медиа — 0px сбоку и 0px сверху, потому что
    // отступ был ТОЛЬКО у контейнера со своей цветовой схемой, а пара колонок
    // с этой ширины идёт вплотную. После правки замер даёт 32px.
    expect(src).toContain(`${bp}:p-8`);
  });

  it.each([
    ['rose', 'lg'],
    ['bloom', 'lg'],
    ['flux', 'lg'],
    ['vanilla', 'lg'],
    ['satin', 'md'],
  ])('%s: медиа тянется на высоту ряда, а не оставляет пустоту', (theme, bp) => {
    const src = read(portOf(theme));

    // Владелец, 19.09: «фотки внутри контейнера не растягиваются на всю высоту
    // и из-за этого есть белое пространство». Замер в живом конструкторе: ряд
    // 206px против медиа 176px — 30px пустоты под картинкой, потому что
    // `aspect-*` фиксирует высоту, а текстовая колонка рядом выше. `h-full`
    // догоняет ряд и НЕ ломает «Высоту»: когда медиа выше текста, высоту
    // по-прежнему задаёт аспект (проверено опытом в браузере).
    expect(src).toContain(`${bp}:h-full`);
  });

  it.each(THEMES)('%s: текст ряда прижат к верху, а не центрирован', (theme) => {
    const src = read(portOf(theme));

    // Владелец, 19.09: «надо чтобы у нижнего был отступ как у верхнего». Замер
    // в его конструкторе: низкий ряд отбивал заголовок на 32px, высокий — на
    // 71px, потому что `justify-center` делит остаток поровну. После правки оба
    // дают 32px. `h-full` обязан остаться: он растягивает колонку на высоту
    // ряда, иначе фон схемы контейнера не закроет ряд целиком.
    expect(src).toContain('h-full');
    expect(src).not.toContain('h-full justify-center');
  });

  it('bloom: на ≥lg ряды идут вплотную и без скруглений', () => {
    const src = read(portOf('bloom'));

    // Ряды вплотную (канон владельца 17.09) — если зазор вернётся, снятие
    // скруглений станет бессмысленным, и проверку ниже надо пересматривать.
    expect(src).toContain('lg:gap-0');
    // Медиа и текстовый контейнер гасят скругления на той же ширине.
    expect(src).toContain('lg:rounded-none');
    // Прежние половинчатые скругления стыка не вернулись.
    expect(src).not.toContain('lg:rounded-l-[var(--radius-media,12px)]');
    expect(src).not.toContain('lg:rounded-r-[var(--radius-media,12px)]');
    expect(src).not.toContain('lg:rounded-l-[var(--radius-card,12px)]');
    expect(src).not.toContain('lg:rounded-r-[var(--radius-card,12px)]');
    // Мобильные скругления остаются: там ряды с зазором.
    expect(src).toContain('rounded-[var(--radius-media,12px)]');
  });
});
