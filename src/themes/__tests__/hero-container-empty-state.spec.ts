import { renderSections } from "../../../scripts/qa/lib/render";

/**
 * Выключатель «Контейнер» секции «Изображение» работает и на ПУСТОЙ секции.
 *
 * Баг тестера 22.09 (satin): «Значение записывается, разметка секции побайтово
 * та же». Замер прода подтвердил ровно это и объяснил причину: свежедобавленный
 * герой рисуется ОТДЕЛЬНОЙ веткой пустого состояния, и плашка «Контейнера» до
 * неё не доходила. bloom и vanilla пустую секцию рисуют обычной веткой, поэтому
 * у них настройка работала — расхождение было 3 темы к 2, и заметили его только
 * на satin.
 *
 * Сторожим ОБА состояния и все пять тем: мерчант щёлкает переключателем сразу
 * после добавления секции, когда содержимого ещё нет.
 */

const ТЕМЫ = ["rose", "bloom", "satin", "vanilla", "flux"] as const;
const КАТАЛОГ = { products: [], collections: [], publications: [] };
const КАРТИНКА = "/images/placeholder.png";

function пара(тема: string, база: Record<string, unknown>): [string, string] {
  const [вкл, выкл] = renderSections(тема, [
    { block: "Hero", props: { ...база, container: "true" }, catalog: КАТАЛОГ },
    { block: "Hero", props: { ...база, container: "false" }, catalog: КАТАЛОГ },
  ]);
  return [вкл?.html ?? "", выкл?.html ?? ""];
}

describe("«Контейнер» героя виден сразу, а не только после наполнения", () => {
  for (const тема of ТЕМЫ) {
    const пусто = { id: "Hero-1", colorScheme: "scheme-1" };

    it(`${тема}: на ПУСТОЙ секции переключатель меняет разметку`, () => {
      const [вкл, выкл] = пара(тема, пусто);
      expect(вкл.length).toBeGreaterThan(0);
      expect(вкл).not.toEqual(выкл);
    });

    it(`${тема}: включённый контейнер даёт плашку, выключенный — нет`, () => {
      const [вкл, выкл] = пара(тема, пусто);
      expect(вкл).toMatch(/rounded-\[var\(--radius-card/);
      // Выключенный контейнер не вправе тащить плашку в разметку.
      const плашкаВыкл = /bg-\[rgb\(var\(--color-bg,[^)]*\)\)\]\/95/.test(выкл);
      expect(плашкаВыкл).toBe(false);
    });

    it(`${тема}: на секции С содержимым переключатель тоже работает`, () => {
      const [вкл, выкл] = пара(тема, {
        ...пусто,
        heading: { text: "Заголовок" },
        text: { content: "Текст" },
        backgroundImages: [КАРТИНКА],
      });
      expect(вкл).not.toEqual(выкл);
    });
  }
});
