/**
 * Демо-кабинет для превью конструктора — ЕДИНЫЙ источник данных, которые
 * секции «Личный кабинет» и «Заказы» показывают мерчанту.
 *
 * Зачем он есть. Тело обеих страниц оживляет inline-скрипт секции
 * (`themes/<t>/src/components/sections/{Account,Orders}Section.astro`), и
 * первое, что он делает, — гость-гейт: `if (!A.getToken()) navTo('/login…')`.
 * В превью покупательской сессии НЕТ и быть не может: iframe конструктора
 * открыт мерчантом, токен покупателя ему никто не выдаёт. А `navTo` внутри
 * iframe не уходит на витрину — он переписывает `?page=` у САМОГО превью, и
 * конструктор перерисовывался страницей «Вход». Замер бага (владелец, 14.09):
 *   preview?page=page-profile → preview?page=%2Flogin,
 *   узлы ["Header-home","Footer-home"], текст «ВХОД В АККАУНТ».
 * Мерчант не видел ни своей секции, ни её настроек.
 *
 * Как чинится. Превью (и ТОЛЬКО превью) кладёт в <head> этот глобал; секция
 * читает его ПЕРЕД гейтом и рисует тело страницы теми же функциями, что и на
 * витрине у вошедшего покупателя, — просто с демо-значениями.
 *
 * ── Почему это не дыра в витрине ───────────────────────────────────────────
 *  1. Глобал инжектит `preview.controller.injectPreviewGlobals` — метод
 *     контроллера превью. Сборка витрины (`generator/build.service.ts`) его не
 *     вызывает и этот модуль не импортирует (гард:
 *     `src/themes/__tests__/account-preview-body.spec.ts`). На live глобала нет
 *     → гость-гейт секции работает ровно как работал.
 *  2. Даже если глобал каким-то образом окажется на витрине, утечь нечему:
 *     здесь ФИКСИРОВАННЫЕ строки-заглушки, вшитые в сервис. Превью-ветка секции
 *     не запрашивает ни `/store/customers/me`, ни `/store/orders` и не получает
 *     токен — она вообще не ходит в сеть. Чужой кабинет показать нечем.
 *  3. Обратная сторона того же: реальные заказы мерчанта/покупателя в превью
 *     не появятся — их некому запросить без токена покупателя. Это осознанный
 *     размен: конструктор показывает РАСКЛАДКУ страницы, а не чьи-то данные.
 */

/** Имя глобала. Одно на всю платформу — секции тем читают именно его. */
export const PREVIEW_ACCOUNT_GLOBAL = '__MERFY_PREVIEW_ACCOUNT__';

/**
 * Демо-покупатель и его заказы. Значения нарочно «образцовые»
 * (example.com, нули в телефоне) — мерчант не спутает их с настоящими.
 * Два заказа, а не один: мерчанту нужно увидеть, как ложатся строки списка
 * и промежуток между ними; на пустом списке проектировать нечего.
 */
export const PREVIEW_ACCOUNT_DEMO = {
  customer: {
    email: 'pokupatel@example.com',
    phone: '+7 (900) 000-00-00',
  },
  orders: [
    { orderNumber: 'DEMO-1024', createdAt: '2026-09-10T10:15:00.000Z' },
    { orderNumber: 'DEMO-1023', createdAt: '2026-09-02T17:40:00.000Z' },
  ],
} as const;

/**
 * Готовый тег для <head> превью. Без `||`-страховки: глобал ставит ровно один
 * инжектор, перетирать нечего.
 */
export const PREVIEW_ACCOUNT_INLINE =
  `<script>window.${PREVIEW_ACCOUNT_GLOBAL} = ` +
  `${JSON.stringify(PREVIEW_ACCOUNT_DEMO)};</script>`;

/**
 * Маркер идемпотентности — ПРИСВАИВАНИЕ, а не имя глобала.
 *
 * Грабли, на которые я наступил при первом заходе (и которые ровно теми же
 * словами описаны в block-root-inline.ts): если сторожить простое вхождение
 * `__MERFY_PREVIEW_ACCOUNT__`, то страница страницы аккаунта «уже
 * проинжектирована» ВСЕГДА — имя глобала есть в ЧТЕНИИ внутри скрипта самой
 * секции (`var preview = window.__MERFY_PREVIEW_ACCOUNT__;`). Инжект молча
 * пропускался, глобала в <head> не появлялось, и превью по-прежнему висело на
 * «Загрузка…». В подстроке ниже есть ` = `, в чтении его нет.
 */
export const PREVIEW_ACCOUNT_MARKER = `window.${PREVIEW_ACCOUNT_GLOBAL} = `;

/**
 * Вставить демо-кабинет в <head>. Отдельная чистая функция (а не три строки
 * внутри приватного метода контроллера) — чтобы гард мог проверить сам факт
 * вставки на РЕАЛЬНОЙ странице аккаунта, где имя глобала уже встречается в
 * теле. Именно этого не хватило, чтобы поймать ошибку маркера тестом.
 */
export function injectPreviewAccountGlobal(html: string): string {
  if (html.includes(PREVIEW_ACCOUNT_MARKER)) return html;
  return html.replace(/<head(\s[^>]*)?>/i, (m) => `${m}${PREVIEW_ACCOUNT_INLINE}`);
}
