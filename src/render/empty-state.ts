export function isPlaceholderImage(url: unknown): boolean {
  if (typeof url !== "string") return true;
  const u = url.trim();
  if (!u) return true;
  if (u.includes("/images/4x/")) return true;
  if (u.includes("/placeholders/")) return true;
  return false;
}

export function isUnsetContent(value: unknown): boolean {
  if (value == null) return true;
  if (typeof value !== "string") return false;
  const t = value.trim();
  if (!t) return true;
  return EMPTY_STATE_COPY.has(t.toLowerCase());
}
