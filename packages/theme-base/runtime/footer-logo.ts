/**
 * «Логотип» секции «Подвал» — своя картинка подвала.
 *
 * Владелец 26.09: «Логотип меняется в хедере, а в подвале я не могу, там
 * стандартный логотип темы стоит. Добавь в футер такую же секцию, чтобы можно
 * было там менять логотип». Шапка берёт логотип из «Настроек темы → Логотип»
 * (загрузка, «Макс. размер 500 КБ»); у подвала поля не было ни в одной теме.
 *
 * Одно правило на пять тем, данными:
 *   • поле панели `{ type: 'image', label: 'Логотип', maxSizeKb: 500 }` —
 *     в puckConfig подвала theme-base и satin (у satin свой конфиг подвала);
 *     литералом, а не импортом: сборка блоков (compile-astro-blocks) не
 *     переписывает импорт theme-base/runtime из пакета темы, а сверка satin с
 *     каноном (satin-sidebar-canon.spec) читает тип поля из исходника;
 *   • порт подвала спрашивает `footerOwnLogo(props)`: непустая строка — рисует
 *     её картинкой на месте логотипа; пусто — рисует ровно то, что рисовал до
 *     поля (vanilla — вордмарк темы, satin — название магазина, bloom — логотип
 *     брендинга или название, rose/flux — логотипа в подвале нет вовсе).
 *
 * Почему отдельный проп, а не служебный `Footer.logo`. Тот заполняет сборка из
 * брендинга (build.service: логотип шапки кладётся в Header И Footer), поэтому
 * загрузка в него перетёрлась бы логотипом шапки при каждой публикации.
 *
 * Размер — та же настройка «Размер» в «Настройках темы → Логотип», что у шапки
 * (`--size-logo-width`, в портах классом высоты из шапки той же темы), отдельной
 * шкалы у подвала нет: мерчант просил только загрузку.
 */

/** Имя пропа секции «Подвал». */
export const FOOTER_OWN_LOGO_PROP = 'customLogo' as const;

/** Загруженный в подвал логотип или '' (поле пустое / не строка). */
export function footerOwnLogo(props: Record<string, unknown> | null | undefined): string {
  const value = props?.[FOOTER_OWN_LOGO_PROP];
  return typeof value === 'string' ? value.trim() : '';
}
