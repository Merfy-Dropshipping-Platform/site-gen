import { renderSections } from "../../../scripts/qa/lib/render";

/**
 * «Основной текст»: выбор размера в панели работает и после первой правки.
 *
 * Владелец 25.09 (долг из списка): в панели «Основного текста» размеры — это
 * поля «Заголовок → Размер заголовка» и «Текст → Размер текста» (конверты
 * `heading.size` / `text.size`). Рядом лежат СКРЫТЫЕ top-level `headingSize` /
 * `textSize`: до 25.09 панель вписывала их значением «Средний» при любой правке
 * секции, и в старых ревизиях они так и лежат. Нормализатор живой цепочки
 * (page-blocks `coerceMainTextProps`) отдавал победу скрытому значению — и выбор
 * мерчанта после первой правки ни на что не влиял.
 *
 * Проверяем тем же путём, что витрина и превью (`live: true`: adaptLegacyProps →
 * blockDefaults темы → порт): секция с выбранными размерами и та же секция со
 * скрытым «Средним» рисуются байт в байт одинаково. Сама проверка не пустая:
 * разные варианты выбора дают разную разметку.
 */

const THEMES = ["rose", "vanilla", "bloom", "flux"] as const;

/** Что лежит в секции после первой правки старой панели. */
const СКРЫТЫЕ = { headingSize: "medium", textSize: "medium" };

const ВЫБОР = [
  { заголовок: "small", текст: "large" },
  { заголовок: "large", текст: "small" },
] as const;

const секция = (заголовок: string, текст: string) => ({
  id: "MainText-1",
  heading: { text: "Заголовок", size: заголовок },
  text: { content: "Текст", size: текст },
});

function отрисовать(theme: string, props: Record<string, unknown>[]): string[] {
  return renderSections(
    theme,
    props.map((p) => ({ block: "MainText", props: p, live: true })),
  ).map((r) => {
    if (r.error) throw new Error(`${theme}: ${r.error}`);
    return r.html ?? "";
  });
}

describe.each(THEMES)("«Основной текст» %s: выбор размера работает после первой правки", (theme) => {
  it.each(ВЫБОР)("заголовок $заголовок, текст $текст — скрытый «Средний» не перебивает выбор", ({ заголовок, текст }) => {
    const [чисто, послеПравки] = отрисовать(theme, [
      секция(заголовок, текст),
      { ...СКРЫТЫЕ, ...секция(заголовок, текст) },
    ]);
    expect(послеПравки).toBe(чисто);
  });

  it("проверка не пустая: разный выбор — разная разметка", () => {
    const [первый, второй] = отрисовать(theme, [
      секция(ВЫБОР[0].заголовок, ВЫБОР[0].текст),
      секция(ВЫБОР[1].заголовок, ВЫБОР[1].текст),
    ]);
    expect(первый).not.toBe(второй);
  });
});
