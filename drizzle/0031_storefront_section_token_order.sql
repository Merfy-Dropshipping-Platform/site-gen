-- Порядок ключей tokens из section.json (блок 4а «Секций и SDK», PR #271): jsonb хранит ключи объекта
-- отсортированными (по длине, потом по алфавиту), поэтому ответ GET /sections отдавал токены секции не в том
-- порядке, что в section.json. При accept порядок имён сохраняется рядом — массивом в отдельной колонке;
-- при чтении реестр собирает объект tokens в этом порядке. Колонка nullable: у строк, принятых раньше,
-- порядка нет — их tokens отдаются как раньше (в порядке jsonb). Новая колонка, данные не меняются — миграция
-- обратно совместима.
ALTER TABLE "storefront_section" ADD COLUMN IF NOT EXISTS "token_order" jsonb;
