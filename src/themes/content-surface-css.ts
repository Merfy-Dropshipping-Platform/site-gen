/** Маркеры `data-block` корней секций, которые держат поверхность контентной страницы. */
export const CONTENT_SURFACE_BLOCKS = ['page'] as const;

/** `[data-block="a"],[data-block="b"],…` — список поверхностей для селекторов. */
const CONTENT_SURFACES = CONTENT_SURFACE_BLOCKS.map(
  (b) => `[data-block="${b}"]`,
).join(',');

/** Та же область, что у sticky-footer: он растягивает `<main>`, мы — то, что внутри. */
const CONTENT_SURFACE_SCOPE = 'body:has(footer):not(:has(main main))';

/**
 * «Последний ребёнок `<main>` — это поверхность (сама секция или обёртка схемы
 * вокруг неё)». Написано СПИСКОМ внутри одного `:has()`, а не `:has(…:has(…))`:
 * вложенный `:has()` невалиден, браузер выбрасывает правило целиком — проверено
 * замером (вариант с вложенностью не сработал ни в одной из 25 клеток).
 */
const LAST_IS_SURFACE = CONTENT_SURFACE_BLOCKS.flatMap((b) => [
  `>*:last-child[data-block="${b}"]`,
  `>*:last-child [data-block="${b}"]`,
]).join(',');

export const CONTENT_SURFACE_CSS =
  // Звено 1: `<main>` контентной страницы → flex-колонка. Без него блочные дети
  // сайзятся по контенту, сколько бы места ни было.
  `${CONTENT_SURFACE_SCOPE}>main:has(${LAST_IS_SURFACE}){display:flex;flex-direction:column}` +
  // Звено 2: обёртка схемы (её вешает composeV2Page) забирает остаток и сама
  // становится колонкой.
  `${CONTENT_SURFACE_SCOPE}>main>*:last-child:has(${CONTENT_SURFACES}){flex:1 0 auto;display:flex;flex-direction:column}` +
  // Звено 3: сама секция растягивается — и внутри обёртки, и когда обёртки нет
  // (блок без `colorScheme`: тогда секция сама последний ребёнок `<main>`).
  `${CONTENT_SURFACE_SCOPE}>main${LAST_IS_SURFACE
    .split(',')
    .join(`,${CONTENT_SURFACE_SCOPE}>main`)}{flex:1 0 auto}`;
