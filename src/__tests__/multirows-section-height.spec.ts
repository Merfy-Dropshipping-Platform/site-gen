/**
 * «Высота» в панели «Мультиряды» действительно меняет высоту рядов.
 *
 * Владелец, 18.09, дословно: «размеры Мультирядов — не работает настройка
 * Высота + отступы между рядами. За высоту почему-то отвечает в параметре Ряд
 * настройка Размер».
 *
 * ЗАМЕР ДО (чтением кода):
 *   • у секции есть поле `size` с подписью «Высота»
 *     (`MultiRows.puckConfig.ts`), у каждого ряда — своё `size` с подписью
 *     «Размер»;
 *   • рендер считал высоту как `aspectKey(row.size, sectionSize)` — per-row
 *     ВСЕГДА главнее;
 *   • при этом дефолты сида кладут `size: 'small'` КАЖДОМУ ряду. Значит
 *     секционное поле не влияло ни на что никогда: его значение затиралось
 *     дефолтом рядов, и высотой де-факто управляла настройка внутри ряда.
 *
 * ПРАВИЛО ПОСЛЕ ПРАВКИ: пока размеры всех рядов одинаковы (никто ничего не
 * выбирал), высоту задаёт секция. Как только мерчант меняет размер хотя бы
 * одному ряду — per-row снова главнее, переопределение работает.
 *
 * Тест читает исходник: поднимать Astro-рендер ради двух строк арифметики
 * дороже, чем польза. Саботаж проверен руками — см. ниже.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(__dirname, "..", "..");
const astro = readFileSync(
  resolve(ROOT, "packages/theme-base/blocks/MultiRows/MultiRows.astro"),
  "utf-8",
);
const cfg = readFileSync(
  resolve(ROOT, "packages/theme-base/blocks/MultiRows/MultiRows.puckConfig.ts"),
  "utf-8",
);

describe("Мультиряды: секционная «Высота» управляет рядами", () => {
  it("САБОТАЖ-ОПОРА: поля «Высота» (секция) и «Размер» (ряд) на месте", () => {
    // Если поля переименуют/уберут, проверки ниже потеряют смысл — пусть
    // сторож упадёт здесь, а не молча позеленеет.
    expect(cfg).toMatch(/size:\s*\{[\s\S]{0,120}label:\s*'Высота'/);
    expect(cfg).toMatch(/size:\s*\{[\s\S]{0,120}label:\s*'Размер'/);
  });

  it("высота ряда считается с оглядкой на то, различаются ли размеры рядов", () => {
    expect(astro).toMatch(/const rowSizes = rowsList\.map/);
    expect(astro).toMatch(/const perRowSizesDiffer = rowSizes\.some/);
    // Главное: в расчёт аспекта уходит НЕ сырой row.size.
    expect(astro).toMatch(
      /rowAspectClass = C\.imageAspect\[aspectKey\(\s*perRowSizesDiffer \? row\.size : undefined\s*,\s*sectionSize\s*\)\]/,
    );
    expect(astro).not.toMatch(/aspectKey\(row\.size, sectionSize\)/);
  });

  it("секционный размер по-прежнему нормализуется к трём значениям", () => {
    // sectionSize — то, что применяется, когда переопределять нечего.
    expect(astro).toMatch(/const sectionSize = \(raw\.size === 'small' \|\| raw\.size === 'large'/);
  });
});

/**
 * Вторая половина жалобы — «отступы между рядами» — НЕ починена и не может быть
 * починена без решения владельца: такой настройки у секции нет вовсе. В панели
 * «Мультирядов» есть только «Отступы» (`padding`) — они про поля секции сверху и
 * снизу, а не про расстояние МЕЖДУ рядами. Добавлять новое поле нельзя: состав
 * параметров секций — канон проекта (`conformance/panel-canon.json`).
 *
 * Этот тест фиксирует факт, чтобы он не потерялся и чтобы никто не «починил»
 * жалобу втихую, добавив поле мимо канона.
 */
describe("Мультиряды: отступы между рядами — открытый вопрос", () => {
  it("в панели секции есть «Отступы» секции и НЕТ отдельной настройки промежутка", () => {
    const fields = cfg.slice(cfg.indexOf("  fields: {"), cfg.indexOf("  defaultProps"));
    expect(fields).toMatch(/padding:\s*\{/);
    expect(fields).not.toMatch(/\b(gap|rowGap|spacing|rowsGap)\s*:/);
  });
});
