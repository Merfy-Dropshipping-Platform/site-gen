/**
 * Медиа ряда не вылезает за свою колонку сетки.
 *
 * Найдено замером живого стенда satin 20.09, уже после выкатки «ряд сплошной»:
 *
 *     дорожки сетки ряда:  312px + 468px = 780   (ширина ряда 780)
 *     фактические ширины:  357px + 468px = 825   ← медиа шире дорожки на 45px
 *     → текстовый блок наезжал на фотографию на 45px
 *
 * ПРИЧИНА. У медиа-контейнера satin стоял `md:h-full` и `aspect-*`, но НЕ было
 * `w-full`. Когда высоту задаёт ряд (а её задаёт текстовая колонка, если она
 * выше), `aspect-ratio` считает ШИРИНУ от высоты — и выдаёт больше, чем
 * отведено дорожкой. Grid такой элемент не обрезает: он просто перекрывает
 * соседа.
 *
 * У остальных четырёх тем `w-full` стоял с самого начала (`group relative
 * w-full lg:h-full`), поэтому дефект был только у satin — и именно поэтому его
 * не видно ни в снимках секций, ни в проверках зазоров: разметка валидна,
 * зазор равен нулю, как и задумано, а перекрытие возникает уже при раскладке.
 *
 * Тест читает исходники портов: геометрию наши гарды считают движком каскада,
 * а он раскладку grid не моделирует — перекрытие ему не видно. Зато условие
 * «рядом с h-full обязан стоять w-full» проверяется дословно и ловит возврат.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(__dirname, '..', '..', '..');
const THEMES = ['rose', 'bloom', 'satin', 'flux', 'vanilla'] as const;

const portSource = (theme: string): string =>
  readFileSync(resolve(ROOT, `themes/${theme}/src/components/sections/MultiRows.astro`), 'utf-8');

/** Код без строчных комментариев: в них классы упоминаются законно. */
const code = (src: string): string => src.replace(/\/\/.*$/gm, '');

describe('«Мультиряды»: медиа помещается в свою колонку', () => {
  it.each(THEMES)('%s: у медиа-контейнера есть и w-full, и h-full', (theme) => {
    const src = code(portSource(theme));

    // Ищем МЕСТО РЕНДЕРА медиа — там, где аспект ряда подставляется в класс
    // (`r.aspectCls` / `row.aspectCls`), а не строку его вычисления
    // (`aspectCls:`). Берём ОКНО вокруг: у satin классы перечислены в
    // `class:list={[...]}` и лежат на РАЗНЫХ строках, поэтому построчный поиск
    // её не находил — первая версия этого гарда падала на satin даже после
    // починки, и поймано это было саботажем, а не чтением.
    const at = src.search(/\b(?:r|row)\.aspectCls\b/);
    expect({ theme, найдено_место_рендера: at > -1 }).toEqual({
      theme,
      найдено_место_рендера: true,
    });
    const around = src.slice(Math.max(0, at - 500), at + 200);

    // Без w-full пропорция считает ширину от высоты и медиа перекрывает текст.
    expect({ theme, есть_w_full: /\bw-full\b/.test(around) }).toEqual({
      theme,
      есть_w_full: true,
    });
    expect({ theme, есть_h_full: /\bh-full\b/.test(around) }).toEqual({
      theme,
      есть_h_full: true,
    });
  });

  it('ОПОРА: во всех темах медиа действительно растягивается по высоте', () => {
    // Если h-full уйдёт совсем, проверка выше начнёт искать несуществующую
    // строку и упадёт по другой причине — пусть это будет видно отдельно.
    for (const theme of THEMES) {
      expect({ theme, есть_h_full: /\bh-full\b/.test(code(portSource(theme))) }).toEqual({
        theme,
        есть_h_full: true,
      });
    }
  });
});
