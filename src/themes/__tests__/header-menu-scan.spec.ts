import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

/**
 * Гард поверх сканера шапки и меню (`scripts/scan-header-menu.mjs`).
 *
 * ПОЧЕМУ СКАНЕР, А НЕ ЕЩЁ ОДИН ТОЧЕЧНЫЙ ГАРД. Волна 21.09 закрыла пункты 24-26
 * документа владельца, на каждый был свой гард, все три остались зелёными — и
 * тестировщик вернул пункты 28 и 29: у пункта с вложенностью оказались ДВЕ
 * стрелки (родная у flux плюс добавленная), нажатие на сам пункт уводило по
 * ссылке и закрывало меню, а в открытой панели логотип рисовался второй раз и
 * не было кнопки закрытия. Гарды этого не видели, потому что каждый пинил СВОЮ
 * правку («класс схемы на корне шторки», «кнопка раскрытия есть»), а не то, что
 * видит человек.
 *
 * Сканер формулирует правила от лица человека («ровно одна стрелка», «нажатие
 * раскрывает, а не уводит», «логотип не дублируется») и гоняет их по решётке
 * 5 тем × 3 типа меню. Новая жалоба тестировщика по шапке должна становиться
 * ПРАВИЛОМ В СКАНЕРЕ, а не отдельным гардом на конкретную правку.
 *
 * Проверено саботажем: возврат второй стрелки у flux, строки-ссылки у rose и
 * логотипа в панели у bloom даёт ровно три нарушения — по одному на правило.
 */
const SCANNER = resolve(__dirname, "..", "..", "..", "scripts", "scan-header-menu.mjs");

type Finding = {
  theme: string;
  menuType: string;
  rule: string;
  заголовок: string;
  problem: string;
};

function runScanner(): Finding[] {
  try {
    const out = execFileSync("node", [SCANNER, "--json"], {
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    });
    return JSON.parse(out) as Finding[];
  } catch (e) {
    // Код возврата 1 = найдены нарушения; они лежат в stdout тем же JSON.
    const err = e as { stdout?: string; message?: string };
    if (err.stdout) return JSON.parse(err.stdout) as Finding[];
    throw e;
  }
}

describe("шапка и меню: сканер видимых правил", () => {
  const findings = runScanner();

  it("нарушений нет ни в одной клетке (5 тем × 3 типа меню)", () => {
    expect(
      findings.map((f) => `${f.theme}/${f.menuType} — ${f.заголовок}: ${f.problem}`),
    ).toEqual([]);
  });

  it("сканер действительно что-то проверяет, а не молчит вхолостую", () => {
    // «Tests: 0 total» уже обманывал: пустой прогон выглядит зелёным. Сканер
    // печатает число клеток и проверок — держим нижнюю границу.
    const out = execFileSync("node", [SCANNER], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    const m = out.match(/(\d+) клеток, (\d+) проверок/);
    expect(m).not.toBeNull();
    expect(Number(m![1])).toBe(15);
    // 80 = 70 прежних + 2 правила бокового меню × 5 тем (баги 4 и 6 документа
    // «баги бокового меню», 22.09). Молча выпавшее правило опустит число.
    expect(Number(m![2])).toBeGreaterThanOrEqual(80);
  });
});
