/**
 * @jest-environment jsdom
 *
 * Шрифт «Группы товаров» — из «Настроек темы»: фильтры, карточки, заголовок.
 *
 * Владелец, 23.09, дважды:
 *   • на вопрос «на макете Inter светлый, у нас в панели шрифт темы —
 *     оставить?»: «надо нормально сделать как в настройках темы сделано»;
 *   • на вопрос про карточки и заголовок каталога: «надо из настроек темы».
 * То есть текст секции — шрифтом ТЕКСТА из «Настроек темы» (Типографика),
 * заголовок — шрифтом ЗАГОЛОВКОВ, как остальной магазин: по умолчанию шрифты
 * темы (rose Manrope, bloom Inter, satin Arsenal, flux Roboto Flex, vanilla
 * Arsenal), а выбрал мерчант другие — и секция следом.
 *
 * Было: у bloom, satin и flux строка фильтров, панели и шторка несли Manrope,
 * скопированный у rose, шторки — шрифт макета; у bloom подзаголовок каталога и
 * счётчик «N товаров» — Manrope литералом при тексте темы Inter.
 *
 * Проверка: секция темы с магазином, у которого есть коллекции, цвета и
 * товары (стенд lib/catalog-dom.ts), скрипты отработали — в DOM и разметка
 * порта, и то, что дорисовал скрипт (карточки, опции фильтров). Для КАЖДОЙ
 * надписи секции мерка lib/font-roles.ts считает по каскаду CSS витрины, чем
 * она будет написана, и из настроек ли это. Роль: внутри h1–h3 — заголовок,
 * остальное — текст. У надписей фильтров сверяется и жирность
 * (`--weight-body`): фильтры — интерфейс, одна жирность текста; у карточек
 * жирность — дизайн темы (bloom светлая).
 *
 * Требует сборки: pnpm build:blocks && pnpm build:theme-sections:all
 */
import {
  ТЕМЫ,
  type Магазин,
  показать,
  поставитьСтенд,
  снять,
} from "./lib/catalog-dom";
import { мерка, надписи, подписьУзла } from "./lib/font-roles";

jest.setTimeout(60_000);
beforeAll(() => поставитьСтенд());
afterAll(() => снять());

const ФОТО =
  "data:image/svg+xml;utf8,%3Csvg%20xmlns%3D%22http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg%22%2F%3E";
const МАГАЗИН: Магазин = {
  коллекции: [
    { id: "c1", title: "Новинки", slug: "novinki" },
    { id: "c2", title: "Лето", slug: "leto" },
  ],
  цвета: ["Черный", "Белый", "Серый"],
  товары: [
    {
      id: "p1",
      title: "Кардиган шерстяной",
      slug: "kardigan",
      basePrice: "4990.00",
      compareAtPrice: "6990.00",
      images: [ФОТО, ФОТО],
    },
    {
      id: "p2",
      title: "Шарф в клетку",
      slug: "sharf",
      basePrice: "1590.00",
      images: [ФОТО],
    },
  ],
};
/** Секция с подзаголовком и быстрым добавлением — все надписи на месте. */
const ПРОПЫ = {
  title: "Каталог",
  subtitle: "Подзаголовок каталога",
  subtitleVisible: true,
  productCard: { quickAdd: "cart", nextPhoto: "true" },
};

/** Где живут фильтры: строка top, панель, блок коллекций, кнопка и шторка. */
const ФИЛЬТРЫ = [
  '[data-nt="catalog-filters"]',
  '[data-nt="filter-sidebar"]',
  '[data-nt="catalog-collections-filter"]',
  "[data-filters-open]",
  "[data-filters-sheet]",
].join(", ");

describe.each(ТЕМЫ)(
  "шрифт «Группы товаров» — из «Настроек темы» — %s",
  (тема) => {
    const м = мерка(тема);

    it("перекрытия «Настроек темы» найдены в выводе tokens-css", () => {
      expect({
        текст: м.РОЛИ.текст.перекрытие,
        заголовок: м.РОЛИ.заголовок.перекрытие,
        жирность: м.РОЛИ.жирность.перекрытие,
      }).toEqual({
        текст: expect.stringContaining("button"),
        заголовок: expect.stringContaining("h1"),
        жирность: expect.stringContaining("button"),
      });
    });

    it("каждая надпись секции — шрифтом из настроек: заголовок — заголовков, остальное — текста", async () => {
      const корень = await показать(тема, ПРОПЫ, true, МАГАЗИН);
      м.взятьCssСтраницы();
      const все = надписи([корень]);
      const чужие = все
        .map((el) => {
          const роль = el.closest("h1, h2, h3")
            ? м.РОЛИ.заголовок
            : м.РОЛИ.текст;
          return { el, роль, шрифт: м.действующее(el, "font-family") };
        })
        .filter((x) => !м.изНастроек(x.шрифт, x.роль))
        .map((x) => ({
          надпись: подписьУзла(x.el),
          ждём: x.роль.переменная,
          шрифт: x.шрифт.значение,
        }));
      expect({
        карточек:
          корень.querySelectorAll('[data-nt="catalog-grid"] > li').length > 1,
        надписей: все.length > 40,
        чужие,
      }).toEqual({ карточек: true, надписей: true, чужие: [] });
    });

    it("надписи фильтров — и жирностью текста из настроек", async () => {
      const корень = await показать(тема, ПРОПЫ, true, МАГАЗИН);
      м.взятьCssСтраницы();
      const все = надписи(корень.querySelectorAll(ФИЛЬТРЫ));
      const чужие = все
        .map((el) => ({ el, жирность: м.действующее(el, "font-weight") }))
        .filter(
          (x) => !м.изНастроек(x.жирность, м.РОЛИ.жирность, (v) => v.trim()),
        )
        .map((x) => ({
          надпись: подписьУзла(x.el),
          жирность: x.жирность.значение,
        }));
      expect({ надписей: все.length > 30, чужие }).toEqual({
        надписей: true,
        чужие: [],
      });
    });
  },
);
