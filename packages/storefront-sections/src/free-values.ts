const ARBITRARY = /^(-?)([a-z][a-z-]*?)-\[([^\]]+)\]$/;
const VALUE_CHARS = /^[0-9a-z.%_,/+*()-]+$/;
const WORD = /[a-z]+(?:-[a-z]+)*/g;

// Своё значение без цвета: утилита из FREE_UTILITIES, значение из чисел, единиц и функций VALUE_WORDS.
export function isFreeValue(utility: string): boolean {
  const match = ARBITRARY.exec(utility);
  if (match === null) return false;
  const [, , root = '', value = ''] = match;
  if (!FREE_UTILITIES.has(root) || !VALUE_CHARS.test(value)) return false;
  return [...value.matchAll(WORD)].every((word) => VALUE_WORDS.has(word[0]));
}

// Своё значение, чей CSS всё-таки красит (страховка поверх списка слов: Tailwind решает тип значения сам).
export const paintsColor = (css: string): boolean =>
  /(?:^|[\s;{])(?:color|background-color|border-color|fill|stroke)\s*:/.test(css);
