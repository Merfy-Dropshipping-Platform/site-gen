/**
 * @jest-environment jsdom
 *
 * «Шрифт текста» и «Жирность текста» из «Настроек темы» доходят до карточек
 * товара — в «Группе товаров» и в «Коллекции товаров» пяти тем.
 *
 * Владелец 23.09: «надо сделать как везде, это такая же секция, по таким же
 * правилам работает, как и все в конструкторе». Замер: ни в одной секции
 * названия и цены карточек не менялись от выбора жирности — перекрытие
 * tokens-css доставало только p/li/button/label, а в карточках это <a>,
 * <span>, <div>. Теперь перекрытие берёт и все надписи карточки товара по
 * метке `[data-nt$="-product-card"]` (та же, что у «Цветовой схемы»
 * карточки), кроме заголовков. Заглушки пустой «Коллекции товаров» rose и
 * vanilla и карточки общего блока получили эту метку.
 *
 * По умолчанию (мерчант ничего не выбрал) перекрытия нет — вид тем прежний,
 * жирность карточек — как в макете (bloom светлая).
 *
 * Проверка: настоящий рендер секций; для каждой надписи карточки мерка
 * lib/font-roles.ts решает, дойдёт ли до неё выбор мерчанта (перекрытие из
 * настоящего вывода tokens-css совпадает с ней или с предком, от которого
 * она наследует, и своё правило узла наследование не обрывает).
 *
 * Требует сборки: pnpm build:blocks && pnpm build:theme-sections:all
 */
import { renderSections } from "../../../scripts/qa/lib/render";
import { ТЕМЫ, показать, поставитьСтенд, снять } from "./lib/catalog-dom";
import { мерка, надписи, подписьУзла } from "./lib/font-roles";

jest.setTimeout(60_000);
beforeAll(() => поставитьСтенд());
afterAll(() => снять());

const ФОТО =
  "data:image/svg+xml;utf8,%3Csvg%20xmlns%3D%22http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg%22%2F%3E";
const ТОВАРЫ = [
  {
    id: "p1",
    title: "Кардиган шерстяной",
    slug: "kardigan",
    basePrice: "4990.00",
    compareAtPrice: "6990.00",
    images: [ФОТО, ФОТО],
  },
  {
    id: "p2",
    title: "Шарф",
    slug: "sharf",
    basePrice: "1590.00",
    images: [ФОТО],
  },
];

const КАРТОЧКА = '[data-nt$="-product-card"]';

/** Надписи карточек, до которых выбор мерчанта не доходит. */
function мимо(м: ReturnType<typeof мерка>, корень: Element) {
  const карточки = [...корень.querySelectorAll(КАРТОЧКА)];
  const все = надписи(карточки).filter(
    (el) => !el.closest("h1,h2,h3,h4,h5,h6"),
  );
  const чужие = все
    .filter(
      (el) =>
        !м.доходитВыбор(el, "font-weight", м.РОЛИ.жирность) ||
        !м.доходитВыбор(el, "font-family", м.РОЛИ.текст),
    )
    .map(подписьУзла);
  return { карточек: карточки.length, надписей: все.length, чужие };
}

describe.each(ТЕМЫ)(
  "шрифт и жирность текста доходят до карточек товара — %s",
  (тема) => {
    const м = мерка(тема);

    it("«Группа товаров»: все надписи карточек", async () => {
      const корень = await показать(тема, {}, true, { товары: ТОВАРЫ });
      м.взятьCssСтраницы();
      const r = мимо(м, корень);
      expect({
        есть: r.карточек > 1 && r.надписей > 3,
        чужие: r.чужие,
      }).toEqual({
        есть: true,
        чужие: [],
      });
    });

    it("«Коллекция товаров»: все надписи карточек (пустая секция — заглушки)", () => {
      снять();
      const [r] = renderSections(тема, [
        { block: "PopularProducts", props: { id: "PopularProducts-1" } },
      ]);
      if (r.error) throw new Error(`${тема}: ${r.error}`);
      document.body.innerHTML = `<main>${(r.html ?? "").replace(
        /<script[^>]*>[\s\S]*?<\/script>/g,
        "",
      )}</main>`;
      м.взятьCssСтраницы();
      const корень = document.querySelector(
        '[data-puck-component-id="PopularProducts-1"]',
      )!;
      const итог = мимо(м, корень);
      expect({
        есть: итог.карточек > 1 && итог.надписей > 1,
        чужие: итог.чужие,
      }).toEqual({
        есть: true,
        чужие: [],
      });
    });
  },
);
